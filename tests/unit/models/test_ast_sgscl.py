@needs_golden
@needs_ast
def test_sgscl_ast_state_dict_matches_reference():
    from rsc_toolkit.models.factory import ModelFactory

    m = ModelFactory.get_model_class("ast_sgscl")(n_cls=4, method="sgscl")
    ref = json.load(open(GOLDEN / "ast_state_dict_shapes.json"))
    ours = {k: list(v.shape) for k, v in m.state_dict().items()}

    def strip_head(d):
        # the unused classification heads of the DeiT skeleton (head/head_dist) exist or not depending on the timm version
        return {k: v for k, v in d.items() if not k.startswith(("v.head", "head"))}

    ref_s = strip_head(ref)
    core = strip_head({k: v for k, v in ours.items()
                       if k.startswith(("v.", "mlp_head.", "domain_mlp_head."))})
    assert not [k for k in ref_s if k not in core], "keys present in the reference are missing"
    assert not {k for k in ref_s if ref_s[k] != core.get(k)}, "shape mismatch"
    assert not [k for k in core if k not in ref_s], "keys not present in the reference"
    # only the extra modules equivalent to set_model are allowed: classifier (= copy of mlp_head), domain_classifier
    others = {k.split(".")[0] for k in ours if k not in core and not k.startswith(("v.head", "head"))}
    assert others == {"classifier", "domain_classifier"}
    # original quirk: in SG-SCL, domain_mlp_head stays at the default 527 dims and remains unused
    assert ours["domain_mlp_head.1.weight"] == [527, 768]


