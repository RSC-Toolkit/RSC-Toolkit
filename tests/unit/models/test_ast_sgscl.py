# ------------------------------------------------------------- two-view SpecAugment
@needs_golden
@pytest.mark.exact_golden  # bitwise comparison — dev machine only (different CPU/BLAS/thread counts diverge in the last digits)
def test_two_view_specaugment_compounds_like_reference():
    """
    The original train() calls in-place SpecAugment twice on the same batch — the second
    view compounds on top of the first view's masks. We reproduce it as view2 = specaug(view1).

    The torch stream must be consumed in the same order as the dump (including generating the input randn),
    because the gate (p >= randn) must see the random number at the same position.
    """
    tw = torch.load(GOLDEN / "twoview_golden.pt")
    torch.manual_seed(11)
    np.random.seed(11)
    random.seed(11)
    x = torch.randn(2, 1, 798, 128)  # [B, 1, time, freq]
    assert torch.equal(x, torch.load(GOLDEN / "twoview_input.pt"))

    sa = SpecAugment(policy="icbhi_ast_sup", mask="mean")
    v1 = apply_specaug_paper(sa, x.squeeze(1))
    v2 = apply_specaug_paper(sa, v1)
    assert torch.equal(v1.unsqueeze(1), tw["v1"])
    assert torch.equal(v2.unsqueeze(1), tw["v2"])
    assert not torch.equal(v1, v2)  # compound masking actually happened


